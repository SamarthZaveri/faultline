"""The corpus of real pipelines: manifest (committed) and pinned checkouts (not committed).

Entries are GitHub repos pinned to a commit, or Kaggle competitions bundling selected public
notebooks. The split unit is the entry's `group` (repo or competition); a group and a Kaggle
author never appear in more than one split, so near-copies by the same person can't leak
across splits.
"""

from __future__ import annotations

import hashlib
import subprocess
from pathlib import Path
from typing import Literal, Protocol

import yaml
from pydantic import BaseModel, Field, model_validator

Split = Literal["train", "dev", "test"]
SPLITS: tuple[Split, ...] = ("train", "dev", "test")
DEFAULT_MANIFEST = Path(__file__).resolve().parents[3] / "corpus" / "manifest.yaml"
DEFAULT_REPOS = DEFAULT_MANIFEST.parent / "repos"
DEFAULT_DEDUPE = DEFAULT_MANIFEST.parent / "dedupe.yaml"
# Only the file types detectors read; skips datasets, images and model weights.
SPARSE_PATTERNS = (
    "*.py",
    "*.ipynb",
    "requirements*.txt",
    "*.yaml",
    "*.yml",
    "*.toml",
    "*.cfg",
    "*.ini",
    "*.env",
)


class KaggleKernel(BaseModel):
    ref: str = Field(pattern=r"^[\w.-]+/[\w.-]+$")  # author/slug
    author: str
    votes: int = 0
    sha256: str | None = None  # content hash at first pull; flags upstream edits later

    @property
    def dirname(self) -> str:
        return self.ref.replace("/", "__")


class CorpusEntry(BaseModel):
    name: str = Field(pattern=r"^[a-z0-9][a-z0-9-]*$")
    source: Literal["github", "kaggle"] = "github"
    split: Split
    group: str = ""  # split unit; defaults to name
    url: str | None = None
    commit: str | None = Field(default=None, pattern=r"^[0-9a-f]{40}$")
    competition: str | None = None
    kernels: list[KaggleKernel] = Field(default_factory=list)
    kinds: list[str] = Field(default_factory=list)
    notes: str = ""

    @model_validator(mode="after")
    def _complete(self) -> CorpusEntry:
        if not self.group:
            self.group = self.name
        if self.source == "github" and not (self.url and self.commit):
            raise ValueError(f"{self.name}: github entries need url and commit")
        if self.source == "kaggle" and not (self.competition and self.kernels):
            raise ValueError(f"{self.name}: kaggle entries need competition and kernels")
        return self


class Manifest(BaseModel):
    repos: list[CorpusEntry]

    @model_validator(mode="after")
    def _invariants(self) -> Manifest:
        names = [r.name for r in self.repos]
        dupes = {n for n in names if names.count(n) > 1}
        if dupes:
            raise ValueError(f"duplicate repo names: {sorted(dupes)}")
        for what, pairs in (
            ("group", [(r.group, r.split) for r in self.repos]),
            ("author", [(k.author, r.split) for r in self.repos for k in r.kernels]),
        ):
            seen: dict[str, str] = {}
            for key, split in pairs:
                if seen.setdefault(key, split) != split:
                    raise ValueError(f"{what} {key!r} appears in both {seen[key]} and {split}")
        return self

    def in_split(self, split: Split) -> list[CorpusEntry]:
        return [r for r in self.repos if r.split == split]


def load_manifest(path: Path = DEFAULT_MANIFEST) -> Manifest:
    return Manifest.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


def save_manifest(manifest: Manifest, path: Path = DEFAULT_MANIFEST) -> None:
    data = manifest.model_dump(mode="json", exclude_defaults=True)
    for entry in data["repos"]:
        entry.setdefault("split", "train")
    header = (
        "# Real pipelines used to train, calibrate and test FaultLine. Generated by `faultline corpus`.\n"
        "# Split unit = group (repo or competition), assigned by a fixed hash before any tuning; the\n"
        "# original 7 repos keep their hand-assigned splits. test is held out (bench --final).\n"
    )
    path.write_text(header + yaml.safe_dump(data, sort_keys=False, width=120), encoding="utf-8", newline="\n")


def _git(args: list[str], cwd: Path) -> str:
    result = subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True)
    return result.stdout.strip()


def fetch(entry: CorpusEntry, repos_dir: Path = DEFAULT_REPOS) -> Path:
    """Shallow, sparse checkout of exactly `entry.commit`. Idempotent."""
    assert entry.url and entry.commit, entry.name
    dest = repos_dir / entry.name
    if (dest / ".git").exists() and _git(["rev-parse", "HEAD"], dest) == entry.commit:
        return dest
    dest.mkdir(parents=True, exist_ok=True)
    if not (dest / ".git").exists():
        _git(["init", "-q"], dest)
        _git(["config", "core.longpaths", "true"], dest)
        _git(["remote", "add", "origin", entry.url], dest)
    _git(["sparse-checkout", "set", "--no-cone", *SPARSE_PATTERNS], dest)
    _git(["fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", entry.commit], dest)
    _git(["checkout", "-q", "--force", "FETCH_HEAD"], dest)
    return dest


class KernelPuller(Protocol):
    def pull(self, ref: str, dest: Path) -> Path: ...


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fetch_kaggle(entry: CorpusEntry, source: KernelPuller, repos_dir: Path = DEFAULT_REPOS) -> CorpusEntry:
    """Pull each kernel into repos_dir/<entry>/<author>__<slug>/. Returns the entry with hashes set."""
    kernels = []
    for k in entry.kernels:
        dest = repos_dir / entry.name / k.dirname
        existing = sorted(p for p in dest.glob("*") if p.suffix in (".ipynb", ".py")) if dest.is_dir() else []
        path = existing[0] if existing else source.pull(k.ref, dest)
        kernels.append(k.model_copy(update={"sha256": k.sha256 or _sha256(path)}))
    return entry.model_copy(update={"kernels": kernels})


def kernel_changed(k: KaggleKernel, repos_dir: Path, entry_name: str) -> bool:
    dest = repos_dir / entry_name / k.dirname
    files = sorted(p for p in dest.glob("*") if p.suffix in (".ipynb", ".py")) if dest.is_dir() else []
    return bool(files and k.sha256 and _sha256(files[0]) != k.sha256)
