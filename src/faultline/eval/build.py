"""Corpus-wide dedupe: drop files that copy an earlier file (train before dev before test)."""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import yaml
from pydantic import BaseModel, Field

from faultline.discovery.sources import iter_sources
from faultline.eval.corpus import SPLITS, Manifest
from faultline.eval.dedupe import find_duplicates


class Duplicate(BaseModel):
    dup_of: str
    kind: str  # exact | near


class DedupeReport(BaseModel):
    excluded: dict[str, Duplicate] = Field(default_factory=dict)  # "entry/path" -> what it copies
    files_by_split: dict[str, int] = Field(default_factory=dict)
    kept_by_split: dict[str, int] = Field(default_factory=dict)
    cross_split: int = 0  # dev/test files that copy a file from an earlier split

    def keys(self) -> set[str]:
        return set(self.excluded)


def dedupe_corpus(manifest: Manifest, repos_dir: Path, threshold: float = 0.8) -> DedupeReport:
    items: list[tuple[str, str]] = []
    split_of: dict[str, str] = {}
    for split in SPLITS:
        for entry in manifest.in_split(split):
            root = repos_dir / entry.name
            if not root.is_dir():
                continue
            for src in iter_sources(root):
                key = f"{entry.name}/{src.path}"
                items.append((key, src.code))
                split_of[key] = split
    dups = find_duplicates(items, threshold)
    report = DedupeReport(
        excluded={k: Duplicate(dup_of=v, kind=kind) for k, (v, kind) in dups.items()},
        files_by_split=dict(Counter(split_of.values())),
    )
    report.kept_by_split = dict(Counter(s for k, s in split_of.items() if k not in dups))
    report.cross_split = sum(split_of[k] != split_of[v] for k, (v, _) in dups.items())
    return report


def save_dedupe(report: DedupeReport, path: Path) -> None:
    path.write_text(
        "# Generated by `faultline corpus dedupe`. Excluded files are skipped by bench.\n"
        + yaml.safe_dump(report.model_dump(mode="json"), sort_keys=True, width=160),
        encoding="utf-8",
        newline="\n",
    )


def load_excluded(path: Path) -> set[str]:
    if not path.exists():
        return set()
    return DedupeReport.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")) or {}).keys()
